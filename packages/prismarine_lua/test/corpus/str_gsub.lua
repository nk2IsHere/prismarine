-- gsub.
print(string.gsub("hello world", "o", "0"))
print(string.gsub("hello world", "o", "0", 1))
print(string.gsub("hello", "", "-"))
print(string.gsub("abc", "%w", "%0%0"))
print(string.gsub("hello world", "(%w+)", "<%1>"))
print(string.gsub("hello world", "(%w+) (%w+)", "%2 %1"))
print(string.gsub("$name is $age", "%$(%w+)", {name = "Jesse", age = 15}))
print(string.gsub("$name is $missing", "%$(%w+)", {name = "Jesse"}))
print(string.gsub("1 2 3", "%d", function(d) return d * 2 end))
print(string.gsub("1 2 3", "%d", function(d) if d == "2" then return nil end return "x" end))
print(pcall(string.gsub, "abc", "b", true))
print(pcall(string.gsub, "abc", "(b)", "%2"))
print(pcall(string.gsub, "abc", "b", "%x"))
print(pcall(string.gsub, "abc", "b", function() return {} end))
print(pcall(string.gsub, "hello", ".", {h = 1, e = true}))
print(string.gsub("abc", "^a", "X"))
print(string.gsub("aaa", "^a", "X"))
print(string.gsub("hello", "l", 5))
print(string.gsub("  x  ", "^%s+", ""))
print(string.gsub("a,b,,c", ",", ";", 2))
print(string.gsub("abc", ".", "%%"))
print(string.gsub("abc", "(a)(b)(c)", "%3%2%1%0"))
