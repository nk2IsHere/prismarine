-- Coroutines: values both ways, status, errors, nesting, wrap.
local co = coroutine.create(function(a, b)
  print("start", a, b)
  local c = coroutine.yield(a + b)
  print("got", c)
  local d, e = coroutine.yield(c * 2)
  print("got2", d, e)
  return "done", 99
end)
print(coroutine.status(co))
print(coroutine.resume(co, 1, 2))
print(coroutine.status(co))
print(coroutine.resume(co, 10))
print(coroutine.resume(co, "x", "y"))
print(coroutine.status(co))
print(coroutine.resume(co))
local gen = coroutine.wrap(function() for i = 1, 3 do coroutine.yield(i) end end)
print(gen(), gen(), gen())
local bad = coroutine.create(function() local x = nil; return x.y end)
print(coroutine.resume(bad))
print(coroutine.status(bad))
print(coroutine.resume(bad))
print(pcall(coroutine.yield, 1))
local main, ismain = coroutine.running()
print(type(main), ismain)
local inner = coroutine.create(function()
  local co2, m = coroutine.running()
  print(type(co2), m, coroutine.status(co2))
end)
coroutine.resume(inner)
local outer
local sub = coroutine.create(function() print("outer is", coroutine.status(outer)) coroutine.yield() end)
outer = coroutine.create(function() coroutine.resume(sub) coroutine.yield("o") end)
print(coroutine.resume(outer))
print(coroutine.status(sub), coroutine.status(outer))
local selfco
selfco = coroutine.create(function() print(coroutine.resume(selfco)) end)
coroutine.resume(selfco)
local function iter(s, i) i = i + 1 if i <= s then coroutine.yield("it" .. i) return i end end
local looper = coroutine.wrap(function() for i in iter, 2, 0 do end return "end" end)
print(looper(), looper(), looper())
local w = coroutine.wrap(function() error("boom") end)
print(pcall(w))
local w2 = coroutine.wrap(function() error({}) end)
local ok, e = pcall(w2)
print(ok, type(e))
print(pcall(coroutine.create, 1))
print(pcall(coroutine.resume, 1))
local many = coroutine.wrap(function(...) local n = 0 for _ in pairs({...}) do n = n + 1 end coroutine.yield(n) return ... end)
print(many(1, 2, 3))
print(many())
