void main() {
  test('mono: VBAP points, arcs cut at the speakers, 360 spreads evenly', () {
    for (final (d, e, want) in _mono) {
      final g = Float64List(6);
      Surround.mono(d, e, 1, 0, g);
      for (var c = 0; c < 6; c++) {
        expect(g[c], closeTo(want[c], 2e-4), reason: 'd $d e $e channel $c');
      }
    }
  });

  test('stereo: distributed halves and discrete points', () {
    for (final (mode, d, e, sep, axis, wl, wr) in _stereo) {
      final l = Float64List(6), r = Float64List(6);
      if (mode == 0) {
        Surround.stereoDistributed(d, e, 0, 1, 0, l, r);
      } else {
        Surround.stereoDiscrete(axis, sep, 1, 0, l, r);
      }
      for (var c = 0; c < 6; c++) {
        final why = 'mode $mode d $d e $e sep $sep axis $axis channel $c';
        expect(l[c], closeTo(wl[c], 2e-4), reason: 'L $why');
        expect(r[c], closeTo(wr[c], 2e-4), reason: 'R $why');
      }
    }
  });
}
