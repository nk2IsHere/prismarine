// docs_index writes or checks the generated indexes of the doc folders with
// one file per entry in the `docs_index` list of tools/lint/config.yaml. An
// empty list leaves nothing to do.
//
//   dart tools/lint/docs_index.dart [--root=<tree>] [--check]
//
// Each entry is a Markdown file <id>.md, which has the form
// <prefix>-<area>-<slug>.md, and starts with a frontmatter block of
// `key: value` lines between `---` lines. The index lists every entry,
// grouped by area, the second part of the id, and sorted by id. The output
// depends only on the entries. Two runs give the same bytes. Two branches
// that add different entries do not touch the same line of an entry. The
// indexes are regenerated at landing. Branches do not edit them.
//
// --check writes nothing. It fails with exit code 1 when an index differs
// from the generated one, an id differs from its file name or is not unique,
// a required frontmatter field is missing or empty or a field holds a value
// outside its set. Entries over the size limit are reported as warnings.
//
// The exit code is 0 when clean or written, 1 when the check failed and 64
// for a usage error.
import 'dart:io';

import 'src/config.dart';

class Folder {
  const Folder({
    required this.dir,
    required this.prefix,
    required this.title,
    required this.intro,
    required this.required,
    required this.columns,
    this.kinds,
    this.areaFirst,
  });

  /// The folder relative to the tree root.
  final String dir;

  /// The id prefix. The prefix `Q` gives ids of the form `Q-<area>-<slug>`.
  final String prefix;
  final String title;
  final List<String> intro;

  /// The frontmatter fields that every entry must have.
  final List<String> required;

  /// The columns of the index table after the id, each a header and a
  /// frontmatter field.
  final List<(String, String)> columns;

  /// The allowed values of `kind`, when the folder has the field.
  final List<String>? kinds;

  /// The pattern of the areas that sort before the rest.
  final RegExp? areaFirst;
}

/// Returns the folders of the `docs_index` list in tools/lint/config.yaml.
/// Each has `dir`, `prefix`, `title`, `intro` lines, `required` fields,
/// `columns` as pairs of header and field and optionally `kinds` and the
/// `area_first` pattern.
List<Folder> foldersOf(LintConfig config) => [
  for (final m in config.docsIndex)
    Folder(
      dir: m['dir'] as String,
      prefix: m['prefix'] as String,
      title: m['title'] as String,
      intro: [for (final l in (m['intro'] as List?) ?? const []) '$l'],
      required: [for (final l in (m['required'] as List?) ?? const []) '$l'],
      columns: [
        for (final c in (m['columns'] as List?) ?? const [])
          ('${(c as List)[0]}', '${c[1]}'),
      ],
      kinds: m['kinds'] == null
          ? null
          : [for (final k in m['kinds'] as List) '$k'],
      areaFirst: m['area_first'] == null ? null : RegExp('${m['area_first']}'),
    ),
];

const maxLines = 30;
const marker =
    '<!-- Generated by tools/lint/docs_index.dart from the entry files; do not edit. -->';

void main(List<String> args) {
  var root = '';
  var check = false;
  for (final a in args) {
    if (a.startsWith('--root=')) {
      root = a.substring(7);
    } else if (a == '--check') {
      check = true;
    } else {
      stderr.writeln(
        'usage: dart tools/lint/docs_index.dart [--root=<tree>] [--check]',
      );
      exit(64);
    }
  }
  if (root.isEmpty) {
    final r = Process.runSync('git', ['rev-parse', '--show-toplevel']);
    if (r.exitCode != 0) {
      stderr.writeln('docs_index: not in a git tree (pass --root)');
      exit(64);
    }
    root = (r.stdout as String).trim();
  }

  var failed = false;
  final folders = foldersOf(LintConfig.of(root));
  if (folders.isEmpty) stdout.writeln('docs_index: no indexed folders');
  for (final f in folders) {
    final problems = <String>[];
    final warnings = <String>[];
    final entries = readEntries('$root/${f.dir}', f, problems, warnings);
    final index = render(f, entries);
    final path = '$root/${f.dir}/README.md';
    final old = File(path).existsSync() ? File(path).readAsStringSync() : null;
    if (check) {
      if (old != index) problems.add('${f.dir}/README.md is not up to date');
    } else if (old != index) {
      File(path).writeAsStringSync(index);
      stdout.writeln('docs_index: wrote ${f.dir}/README.md');
    }
    for (final w in warnings) {
      stdout.writeln('docs_index: warning: $w');
    }
    for (final p in problems) {
      stdout.writeln('docs_index: $p');
    }
    stdout.writeln(
      'docs_index: ${f.dir}: ${entries.length} entries, '
      '${problems.length} problem(s), ${warnings.length} warning(s)',
    );
    failed |= problems.isNotEmpty;
  }
  exit(failed ? 1 : 0);
}

class Entry {
  Entry(this.file, this.fields);
  final String file;
  final Map<String, String> fields;
  String get id => fields['id'] ?? '';
  String get area => id.split('-').length > 1 ? id.split('-')[1] : '';
}

List<Entry> readEntries(
  String dir,
  Folder f,
  List<String> problems,
  List<String> warnings,
) {
  final d = Directory(dir);
  if (!d.existsSync()) {
    problems.add('$dir does not exist');
    return [];
  }
  final idRe = RegExp('^${f.prefix}-[a-z0-9]+(-[a-z0-9]+)+\$');
  final out = <Entry>[];
  final seen = <String, String>{};
  final files =
      d
          .listSync()
          .whereType<File>()
          .map((e) => e.uri.pathSegments.last)
          .where((n) => n.endsWith('.md') && n != 'README.md')
          .toList()
        ..sort();
  for (final name in files) {
    final text = File('$dir/$name').readAsStringSync();
    final lines = text.split('\n');
    if (lines.isNotEmpty && lines.last.isEmpty) lines.removeLast();
    final fields = frontmatter(lines);
    if (fields == null) {
      problems.add('$name: no frontmatter');
      continue;
    }
    final e = Entry(name, fields);
    for (final k in f.required) {
      if ((fields[k] ?? '').isEmpty) problems.add('$name: no "$k"');
    }
    if (e.id.isNotEmpty) {
      if ('${e.id}.md' != name) {
        problems.add('$name: id ${e.id} is not the file name');
      }
      if (!idRe.hasMatch(e.id)) {
        problems.add(
          '$name: id ${e.id} is not ${f.prefix}-<area>-<slug> in lower case',
        );
      }
      final prev = seen[e.id];
      if (prev != null) problems.add('$name: id ${e.id} also in $prev');
      seen[e.id] = name;
    }
    final kinds = f.kinds;
    if (kinds != null &&
        fields['kind'] != null &&
        !kinds.contains(fields['kind'])) {
      problems.add(
        '$name: kind "${fields['kind']}" is not one of ${kinds.join(', ')}',
      );
    }
    if (!RegExp(r'^\d{4}-\d{2}-\d{2}$').hasMatch(fields['added'] ?? '')) {
      problems.add('$name: added "${fields['added']}" is not yyyy-mm-dd');
    }
    if (lines.length > maxLines) {
      warnings.add('$name: ${lines.length} lines (limit $maxLines)');
    }
    out.add(e);
  }
  return out;
}

/// Returns the `key: value` lines between the first two `---` lines, or
/// null.
Map<String, String>? frontmatter(List<String> lines) {
  if (lines.isEmpty || lines.first.trim() != '---') return null;
  final m = <String, String>{};
  for (var i = 1; i < lines.length; i++) {
    final l = lines[i];
    if (l.trim() == '---') return m;
    final c = l.indexOf(':');
    if (c <= 0) continue;
    m[l.substring(0, c).trim()] = l.substring(c + 1).trim();
  }
  return null;
}

/// Orders the areas that match [first] before the rest and each group by
/// name.
int areaOrder(String a, String b, [RegExp? first]) {
  final ea = first?.hasMatch(a) ?? false;
  final eb = first?.hasMatch(b) ?? false;
  if (ea != eb) return ea ? -1 : 1;
  return a.compareTo(b);
}

String cell(String s) => s.replaceAll('|', r'\|');

String render(Folder f, List<Entry> entries) {
  final b = StringBuffer()
    ..writeln('# ${f.title}')
    ..writeln()
    ..writeln(marker)
    ..writeln();
  for (final l in f.intro) {
    b.writeln(l);
  }
  final areas = entries.map((e) => e.area).toSet().toList()
    ..sort((a, b) => areaOrder(a, b, f.areaFirst));
  b
    ..writeln()
    ..writeln('${entries.length} entries.');
  for (final a in areas) {
    final rows = entries.where((e) => e.area == a).toList()
      ..sort((x, y) => x.id.compareTo(y.id));
    b
      ..writeln()
      ..writeln('## $a')
      ..writeln()
      ..writeln('| Id | ${f.columns.map((c) => c.$1).join(' | ')} |')
      ..writeln('|---|${f.columns.map((_) => '---').join('|')}|');
    for (final e in rows) {
      final cols = f.columns.map((c) => cell(e.fields[c.$2] ?? '')).join(' | ');
      b.writeln('| [${e.id}](${e.file}) | $cols |');
    }
  }
  return b.toString();
}
